"""Compaction measurements for #158: what file size costs, and what streaming buys.

Internal, like the rest of `benchmarks/`. Every number it prints is measured
here and now, on synthetic streams shaped like real ones (#158 chose synthetic:
no S3 egress, fully reproducible). The shapes, generated by DuckDB SQL so the
data is deterministic and nothing extra is installed:

    trades    a tick stream: increasing ts, 40 symbols, side, price, size, id
    depth     order-book snapshots: 10 symbols x 2 sides x 20 levels per ts
    adsb      aircraft positions: 3,000 icao codes, lat/lon/alt/speed/heading
    posts     social posts: 50,000 authors, 20-80 word texts, a like count

Phases, each runnable alone:

    uv run python benchmarks/compaction.py ratios     # on-disk vs Arrow; seal estimate drift
    uv run python benchmarks/compaction.py layouts    # build today's and 512 MB layouts
    uv run python benchmarks/compaction.py queries    # query cost per layout, local and S3
    uv run python benchmarks/compaction.py memory     # peak RSS: today's merge vs streamed

`layouts` writes about 7 GB under --root (default `$TMPDIR/litelink-compaction`);
`queries` and `memory` read what it wrote. `queries` drops the page cache with
`sudo` for its cold runs, and uploads the layouts to rustfs (`just rustfs`) for
its S3 runs unless given --no-s3; `--stream depth` reruns one stream.
"""

from __future__ import annotations

import argparse
import bisect
import json
import statistics
import subprocess
import sys
import tempfile
import time
from pathlib import Path

import duckdb
import pyarrow as pa
import pyarrow.parquet as pq

MIB = 1 << 20
# Today's compaction target: COMPACT_MULTIPLE x the default 8 MiB seal, in
# Arrow bytes held in memory.
TODAY_ARROW_BYTES = 64 * MIB
SEAL_ARROW_BYTES = 8 * MIB
# The proposed alternative: a target on disk, in Iceberg's usual range.
DISK_TARGET = 512 * 10**6
COMPRESSION = "zstd"  # litelink's default codec (`LogConfig.compression`)

T0 = 1_780_000_000_000_000  # microseconds

# Each stream is SQL over `range(lo, hi) t(o)`, `o` being the offset. Rows come
# out in offset order, and for every stream ts follows offset, so `sort_by=ts`
# is arrival order — the common case. `depth` is also measured sorted by
# (symbol, ts), which is not.
STREAMS: dict[str, str] = {
    "trades": f"""
        SELECT o AS litelink_offset,
               {T0} + o * 500 + (h(o) % 400) AS ts,
               'S' || (h(o * 7) % 40) AS symbol,
               CASE WHEN h(o * 3) % 2 = 0 THEN 'buy' ELSE 'sell' END AS side,
               round(100 + 50 * sin(o / 1e6) + (h(o * 11) % 1000) / 1000.0, 2) AS price,
               round(exp((h(o * 13) % 1000) / 250.0) / 10, 4) AS size,
               1000000 + o AS trade_id
        FROM range({{lo}}, {{hi}}) t(o)""",
    "depth": f"""
        SELECT o AS litelink_offset,
               {T0} + (o // 400) * 100000 AS ts,
               'S' || ((o // 40) % 10) AS symbol,
               CASE WHEN (o // 20) % 2 = 0 THEN 'bid' ELSE 'ask' END AS side,
               CAST(o % 20 AS TINYINT) AS level,
               round(100 + 10 * sin((o // 400) / 1e4)
                     + CASE WHEN (o // 20) % 2 = 0 THEN -1 ELSE 1 END * (o % 20) * 0.01, 2) AS price,
               round((h(o) % 10000) / 100.0, 2) AS size
        FROM range({{lo}}, {{hi}}) t(o)""",
    "adsb": f"""
        SELECT o AS litelink_offset,
               {T0} + o * 2000 AS ts,
               printf('%06x', 10000000 + h(o * 5) % 3000) AS icao,
               round(37 + (h(o * 5) % 3000) / 1000.0 + sin(o / 5e5), 5) AS lat,
               round(-122 + (h(o * 5) % 3000) / 1000.0 + cos(o / 5e5), 5) AS lon,
               CAST(25 * ((h(o * 17) % 1600)) AS INTEGER) AS alt,
               CAST(200 + (h(o * 19) % 300) AS FLOAT) AS speed,
               CAST(h(o * 23) % 360 AS FLOAT) AS heading
        FROM range({{lo}}, {{hi}}) t(o)""",
    "posts": f"""
        SELECT o AS litelink_offset,
               {T0} + o * 20000 AS ts,
               'user_' || (h(o * 29) % 50000) AS author,
               array_to_string(list_transform(range(20 + h(o) % 60),
                   i -> 'w' || (h(o * 31 + i) % 5000)), ' ') AS text,
               CAST(h(o * 37) % 1000 AS INTEGER) AS likes
        FROM range({{lo}}, {{hi}}) t(o)""",
}


def connect() -> duckdb.DuckDBPyConnection:
    """A connection with `h(x)`: a deterministic hash as a signed BIGINT, so
    arithmetic on it stays BIGINT (DuckDB's `hash` is UBIGINT)."""
    con = duckdb.connect()
    con.execute("CREATE MACRO h(x) AS CAST(hash(x) % 1000000007 AS BIGINT)")
    return con


def generate(con: duckdb.DuckDBPyConnection, stream: str, lo: int, hi: int) -> pa.Table:
    return con.sql(STREAMS[stream].format(lo=lo, hi=hi)).arrow().read_all()


def rows_for(con: duckdb.DuckDBPyConnection, stream: str, arrow_bytes: int) -> int:
    """Rows whose Arrow size is about `arrow_bytes`, from a sample."""
    sample = generate(con, stream, 0, 100_000)
    return max(1, int(arrow_bytes / (sample.nbytes / sample.num_rows)))


def write(table: pa.Table, path: Path) -> int:
    """As litelink writes a data file: `pq.write_table`, its codec, defaults."""
    pq.write_table(table, path, compression=COMPRESSION)
    return path.stat().st_size


# -- ratios ---------------------------------------------------------------------


def ratios() -> None:
    """How small 64 MiB of Arrow ends up on disk, per stream and sort order;
    and how far the seal trigger's estimate drifts from Arrow's `nbytes`, and
    what it costs per row."""
    from litelink._buffer import _measurer  # the seal trigger's estimate

    con = connect()
    print("RATIOS  one compacted file at today's target: 64 MiB of Arrow, zstd\n")
    print(
        f"  {'stream':10s} {'sorted by':14s} {'rows':>10s} {'arrow':>10s} {'disk':>10s} {'ratio':>7s}"
    )
    with tempfile.TemporaryDirectory() as tmp:
        for stream in STREAMS:
            rows = rows_for(con, stream, TODAY_ARROW_BYTES)
            table = generate(con, stream, 0, rows)
            orders = [("ts",)] + ([("symbol", "ts")] if stream == "depth" else [])
            for order in orders:
                sorted_ = table.sort_by([(c, "ascending") for c in order])
                disk = write(sorted_, Path(tmp) / f"{stream}.parquet")
                print(
                    f"  {stream:10s} {','.join(order):14s} {rows:>10,} "
                    f"{table.nbytes / MIB:>8.1f}Mi {disk / MIB:>8.2f}Mi "
                    f"{table.nbytes / disk:>6.1f}x"
                )

    print("\nDRIFT   the seal trigger's per-row estimate against Arrow's nbytes\n")
    print(
        f"  {'stream':10s} {'estimate':>10s} {'nbytes':>10s} {'drift':>8s} {'cost/row':>10s}"
    )
    for stream in STREAMS:
        table = generate(con, stream, 0, 20_000)
        user = table.drop_columns(["litelink_offset"])
        measure = _measurer(user.schema)
        rows = [tuple(r.values()) for r in user.to_pylist()]
        started = time.perf_counter()
        estimate = sum(measure(r) for r in rows)
        cost = (time.perf_counter() - started) / len(rows) * 1e6
        actual = user.nbytes
        print(
            f"  {stream:10s} {estimate / MIB:>8.2f}Mi {actual / MIB:>8.2f}Mi "
            f"{(estimate - actual) / actual * 100:>+7.1f}% {cost:>8.2f}us"
        )


# -- layouts --------------------------------------------------------------------

# The two streams the layouts are built for: one whose sort is arrival order,
# and one whose isn't. About a gigabyte on disk each — two 512 MB files against
# a hundred or more of today's.
LAYOUT_STREAMS: dict[str, tuple[str, ...]] = {
    "trades": ("ts",),
    "depth": ("symbol", "ts"),
}
DATASET_DISK = 10**9
ROW_GROUP_ROWS = 1 << 20  # pyarrow's default `row_group_size`


def sorted_by(table: pa.Table, order: tuple[str, ...]) -> pa.Table:
    return table.sort_by([(c, "ascending") for c in order])


class Rolling:
    """A streamed append: one open `ParquetWriter` per output file, rolled over
    once the bytes it has written reach `target` — the on-disk target #158
    proposes, read off the sink with `tell()` and never estimated.

    With `group_rows`, appends are buffered into row groups of that many rows;
    without, each append is its own row group, as appending whole input files
    makes it."""

    def __init__(
        self,
        directory: Path,
        target: int,
        group_rows: int | None = None,
        name: str = "",
    ) -> None:
        self.directory, self.target, self.group_rows = directory, target, group_rows
        self.name = name
        self.files: list[Path] = []
        self.writer: pq.ParquetWriter | None = None
        self.sink: pa.NativeFile | None = None
        self.pending: list[pa.Table] = []
        self.pending_rows = 0
        directory.mkdir(parents=True, exist_ok=True)

    def append(self, table: pa.Table) -> None:
        if self.group_rows is None:
            self._write(table)
            return

        self.pending.append(table)
        self.pending_rows += table.num_rows
        while self.pending_rows >= self.group_rows:
            whole = pa.concat_tables(self.pending)
            self._write(whole.slice(0, self.group_rows))
            rest = whole.slice(self.group_rows)
            self.pending, self.pending_rows = [rest], rest.num_rows

    def _write(self, table: pa.Table) -> None:
        if self.writer is None:
            path = self.directory / f"{self.name}{len(self.files):05d}.parquet"
            self.files.append(path)
            self.sink = pa.OSFile(str(path), "wb")
            self.writer = pq.ParquetWriter(
                self.sink, table.schema, compression=COMPRESSION
            )

        self.writer.write_table(table, row_group_size=len(table) or 1)
        assert self.sink is not None
        if self.sink.tell() >= self.target:
            self._roll()

    def _roll(self) -> None:
        assert self.writer is not None and self.sink is not None
        self.writer.close()
        self.sink.close()
        self.writer = self.sink = None

    def close(self) -> list[Path]:
        if self.pending_rows:
            self._write(pa.concat_tables(self.pending))
            self.pending, self.pending_rows = [], 0

        if self.writer is not None:
            self._roll()

        return self.files


def file_stats(path: Path) -> dict:
    """Per-file min/max of the columns queries prune on: what an Iceberg
    manifest holds for the file, so a query can skip files as a scan would."""
    meta = pq.ParquetFile(path).metadata
    names = meta.schema.to_arrow_schema().names
    stats: dict = {
        "path": str(path),
        "bytes": path.stat().st_size,
        "rows": meta.num_rows,
        "row_groups": meta.num_row_groups,
    }
    for col in ("litelink_offset", "ts", "symbol"):
        i = names.index(col)
        groups = [
            meta.row_group(g).column(i).statistics for g in range(meta.num_row_groups)
        ]
        stats[col] = [min(s.min for s in groups), max(s.max for s in groups)]

    return stats


def layouts(root: Path) -> None:
    """Build each stream's layouts from one pass over the same rows:

        today       what compaction writes now: 8 seals (8 MiB of Arrow each)
                    concatenated, re-sorted, one `write_table` — 64 MiB of Arrow
        512M-seal   a streamed append of the seals, rolled at 512 MB on disk;
                    each seal its own row group
        512M-1M     the same append, rebatched into 1 Mi-row groups
        512M-sorted (depth only) today's files packed greedily into 512 MB bins,
                    each bin k-way merged by (symbol, ts) into one file
        512M-blocks (depth only) a streamed append of today's files, each one
                    row group: sorted within a block, offsets kept local

    Then `layout.json` per layout: every file's size, row groups and the
    min/max a manifest would hold."""
    con = connect()
    for stream, order in LAYOUT_STREAMS.items():
        seal_rows = rows_for(con, stream, SEAL_ARROW_BYTES)
        block = seal_rows * (TODAY_ARROW_BYTES // SEAL_ARROW_BYTES)
        probe = write(
            sorted_by(generate(con, stream, 0, block), order), root / "probe.parquet"
        )
        (root / "probe.parquet").unlink()
        blocks = -(-DATASET_DISK // probe)
        print(
            f"{stream}: {blocks} blocks of {block:,} rows ({blocks * block:,} rows), seals of {seal_rows:,}"
        )

        today = root / stream / "today"
        today.mkdir(parents=True, exist_ok=True)
        seal_rg = Rolling(root / stream / "512M-seal", DISK_TARGET)
        big_rg = (
            Rolling(root / stream / "512M-1M", DISK_TARGET, ROW_GROUP_ROWS)
            if stream == "trades"
            else None
        )
        timings = {"today": 0.0, "512M-seal": 0.0, "512M-1M": 0.0}
        for b in range(blocks):
            seals = [
                sorted_by(generate(con, stream, lo, lo + seal_rows), order)
                for lo in range(b * block, (b + 1) * block, seal_rows)
            ]
            started = time.perf_counter()
            write(sorted_by(pa.concat_tables(seals), order), today / f"{b:05d}.parquet")
            timings["today"] += time.perf_counter() - started
            for name, rolling in (("512M-seal", seal_rg), ("512M-1M", big_rg)):
                if rolling is None:
                    continue

                started = time.perf_counter()
                for seal in seals:
                    rolling.append(seal)

                timings[name] += time.perf_counter() - started

            if b % 20 == 0:
                print(f"  block {b}/{blocks}", flush=True)

        seal_rg.close()
        if big_rg is not None:
            big_rg.close()

        if stream == "depth":
            started = time.perf_counter()
            out = root / stream / "512M-sorted"
            for i, inputs in enumerate(
                pack(sorted(today.glob("*.parquet")), DISK_TARGET)
            ):
                k_way_merge(inputs, out, order, name=f"{i:03d}-")

            timings["512M-sorted"] = time.perf_counter() - started
            started = time.perf_counter()
            blocks_rg = Rolling(root / stream / "512M-blocks", DISK_TARGET)
            for f in sorted(today.glob("*.parquet")):
                blocks_rg.append(pq.read_table(f))

            blocks_rg.close()
            timings["512M-blocks"] = time.perf_counter() - started

        for name in sorted(p.name for p in (root / stream).iterdir()):
            files = sorted((root / stream / name).glob("*.parquet"))
            stats = [file_stats(f) for f in files]
            (root / stream / name / "layout.json").write_text(json.dumps(stats))
            sizes = [s["bytes"] for s in stats]
            print(
                f"  {name:12s} {len(files):4d} files  {sum(sizes) / 1e6:8.1f} MB  "
                f"largest {max(sizes) / 1e6:7.1f} MB  row groups {sum(s['row_groups'] for s in stats):5d}  "
                f"write {timings.get(name, 0):6.1f}s"
            )


def pack(files: list[Path], target: int) -> list[list[Path]]:
    """Greedy bins of whole, adjacent files: a new bin once the next file would
    take this one past `target` bytes on disk."""
    bins: list[list[Path]] = [[]]
    size = 0
    for f in files:
        n = f.stat().st_size
        if bins[-1] and size + n > target:
            bins.append([])
            size = 0

        bins[-1].append(f)
        size += n

    return bins


def k_way_merge(
    inputs: list[Path],
    out: Path,
    order: tuple[str, ...],
    name: str = "",
    batch_rows: int = 65_536,
) -> list[Path]:
    """Merge inputs each already sorted by `order` into one sorted output, in
    memory bounded by one batch per input.

    Each round takes, from every input's current batch, the rows at or below
    the smallest of the batches' last keys — everything that can come next —
    sorts just those and appends them. The input that set the bound is used up,
    so every round advances at least one."""
    readers = [pq.ParquetFile(p).iter_batches(batch_size=batch_rows) for p in inputs]
    heads: list[pa.Table | None] = [None] * len(readers)

    def refill(i: int) -> None:
        batch = next(readers[i], None)
        heads[i] = None if batch is None else pa.Table.from_batches([batch])

    def key(table: pa.Table, row: int) -> tuple:
        return tuple(table.column(c)[row].as_py() for c in order)

    for i in range(len(readers)):
        refill(i)

    rolling = Rolling(out, 1 << 62, ROW_GROUP_ROWS, name)
    while any(h is not None for h in heads):
        live = [h for h in heads if h is not None]
        bound = min(key(h, h.num_rows - 1) for h in live)
        taken = []
        for i, head in enumerate(heads):
            if head is None:
                continue

            cut = bisect.bisect_right(
                range(head.num_rows), bound, key=lambda r, h=head: key(h, r)
            )
            if cut:
                taken.append(head.slice(0, cut))

            if cut == head.num_rows:
                refill(i)
            else:
                heads[i] = head.slice(cut)

        rolling.append(sorted_by(pa.concat_tables(taken), order))

    return rolling.close()


def external_sort(
    inputs: list[Path], out: Path, order: tuple[str, ...], memory_limit: str = "1GB"
) -> list[Path]:
    """Re-sort `inputs` by `order` in bounded memory: DuckDB's external sort,
    streamed out in record batches through the same writer the other layouts use."""
    con = duckdb.connect(
        config={
            "memory_limit": memory_limit,
            "threads": 2,
            "temp_directory": str(out.parent / ".spill"),
        }
    )
    files = ", ".join(f"'{p}'" for p in inputs)
    reader = con.execute(
        f"SELECT * FROM read_parquet([{files}]) ORDER BY {', '.join(order)}"
    ).fetch_record_batch(65_536)
    rolling = Rolling(out, DISK_TARGET, ROW_GROUP_ROWS)
    for batch in reader:
        rolling.append(pa.Table.from_batches([batch]))

    return rolling.close()


# -- queries --------------------------------------------------------------------

# Each query: a name, SQL over `{files}`, and the predicate a manifest prunes
# files on — (column, lo, hi) in fractions of the dataset's span, resolved
# against the layout's stats — or None for a query that reads every file.
Prune = tuple[str, float, float | None]
QUERIES: dict[str, list[tuple[str, str, Prune | None]]] = {
    "trades": [
        ("count", "SELECT count(*) FROM {files}", None),
        (
            "group by symbol",
            "SELECT symbol, sum(size), avg(price) FROM {files} GROUP BY 1",
            None,
        ),
        (
            "non-sort filter",
            "SELECT avg(price), sum(size) FROM {files} WHERE symbol = 'S7'",
            None,
        ),
        (
            "ts range 0.1%",
            "SELECT sum(price * size) FROM {files} WHERE ts BETWEEN {lo} AND {hi}",
            ("ts", 0.5, 0.501),
        ),
        (
            "ts range 5%",
            "SELECT sum(price * size) FROM {files} WHERE ts BETWEEN {lo} AND {hi}",
            ("ts", 0.5, 0.55),
        ),
        (
            "offset range 100k",
            "SELECT * FROM {files} WHERE litelink_offset BETWEEN {lo} AND {hi}",
            ("litelink_offset", 0.5, None),
        ),
    ],
    "depth": [
        ("count", "SELECT count(*) FROM {files}", None),
        (
            "group by symbol",
            "SELECT symbol, side, avg(price) FROM {files} GROUP BY 1, 2",
            None,
        ),
        ("non-sort filter", "SELECT avg(size) FROM {files} WHERE level = 0", None),
        (
            "symbol + ts 1%",
            "SELECT avg(price) FROM {files} WHERE symbol = 'S3' AND ts BETWEEN {lo} AND {hi}",
            ("ts", 0.5, 0.51),
        ),
        (
            "offset range 100k",
            "SELECT * FROM {files} WHERE litelink_offset BETWEEN {lo} AND {hi}",
            ("litelink_offset", 0.5, None),
        ),
    ],
}


def resolve(stats: list[dict], prune: Prune | None) -> tuple[list[dict], int, int]:
    """The files a manifest would leave, and the predicate's bounds."""
    if prune is None:
        return stats, 0, 0

    col, lo_f, hi_f = prune
    first = min(s[col][0] for s in stats)
    last = max(s[col][1] for s in stats)
    lo = int(first + (last - first) * lo_f)
    hi = lo + 100_000 if hi_f is None else int(first + (last - first) * hi_f)
    return [s for s in stats if s[col][1] >= lo and s[col][0] <= hi], lo, hi


def drop_caches() -> None:
    subprocess.run(
        ["sudo", "sh", "-c", "sync; echo 3 > /proc/sys/vm/drop_caches"], check=True
    )


S3_ENDPOINT = "127.0.0.1:9000"
S3_BUCKET = "litelink-bench"


def s3_connection() -> duckdb.DuckDBPyConnection:
    con = duckdb.connect(config={"threads": 2})
    con.execute(f"""
        CREATE SECRET (TYPE s3, KEY_ID 'litelink', SECRET 'litelink-secret', REGION 'us-east-1',
                       ENDPOINT '{S3_ENDPOINT}', URL_STYLE 'path', USE_SSL false)""")
    con.execute("SET enable_external_file_cache = false")
    con.execute("CALL enable_logging('HTTP')")
    return con


def upload(root: Path) -> None:
    import s3fs

    fs = s3fs.S3FileSystem(
        key="litelink",
        secret="litelink-secret",
        client_kwargs={
            "endpoint_url": f"http://{S3_ENDPOINT}",
            "region_name": "us-east-1",
        },
    )
    if not fs.exists(S3_BUCKET):
        fs.mkdir(S3_BUCKET)

    for layout in sorted(root.glob("*/*/layout.json")):
        prefix = f"{S3_BUCKET}/{layout.parent.relative_to(root)}"
        if fs.exists(f"{prefix}/layout.json"):
            continue

        for f in sorted(layout.parent.glob("*.parquet")):
            fs.put_file(str(f), f"{prefix}/{f.name}")

        fs.put_file(str(layout), f"{prefix}/layout.json")
        print(f"  uploaded {prefix}", flush=True)


def run(con: duckdb.DuckDBPyConnection, sql: str) -> float:
    started = time.perf_counter()
    con.execute(sql).fetchall()
    return time.perf_counter() - started


def queries(root: Path, reps: int, s3: bool, streams: list[str]) -> None:
    """Every query on every layout: local warm (median of `reps`), local cold
    (page cache dropped first), and over S3 — rustfs on this box, so the time
    is request handling without network latency, and the request count is the
    figure that scales with a real round trip."""
    if s3:
        upload(root)

    results = []
    for stream in streams:
        names = sorted(p.parent.name for p in (root / stream).glob("*/layout.json"))
        print(f"\n{stream}")
        header = f"  {'query':20s} {'layout':12s} {'files':>6s} {'warm ms':>9s} {'cold ms':>9s}"
        if s3:
            header += f" {'s3 ms':>9s} {'requests':>9s} {'MB read':>8s}"

        print(header)
        for qname, template, prune in QUERIES[stream]:
            for name in names:
                stats = json.loads((root / stream / name / "layout.json").read_text())
                kept, lo, hi = resolve(stats, prune)

                def sql(paths: list[str], template=template, lo=lo, hi=hi) -> str:
                    listed = ", ".join(f"'{p}'" for p in paths)
                    return template.format(
                        files=f"read_parquet([{listed}])", lo=lo, hi=hi
                    )

                local = sql([s["path"] for s in kept])
                con = duckdb.connect(config={"threads": 2})
                run(con, local)
                warm = statistics.median(run(con, local) for _ in range(reps))
                con.close()
                drop_caches()
                con = duckdb.connect(config={"threads": 2})
                cold = run(con, local)
                con.close()
                row = {
                    "stream": stream,
                    "query": qname,
                    "layout": name,
                    "files": len(kept),
                    "warm_ms": warm * 1e3,
                    "cold_ms": cold * 1e3,
                }
                line = f"  {qname:20s} {name:12s} {len(kept):6d} {warm * 1e3:9.1f} {cold * 1e3:9.1f}"
                if s3:
                    remote = sql(
                        [
                            f"s3://{S3_BUCKET}/{stream}/{name}/{Path(s['path']).name}"
                            for s in kept
                        ]
                    )
                    times, requests, read = [], 0, 0
                    for _ in range(max(1, reps // 2)):
                        con = s3_connection()
                        times.append(run(con, remote))
                        counted = con.execute("""
                            SELECT count(*), coalesce(sum(TRY_CAST(response.headers['content-length'] AS BIGINT))
                                     FILTER (WHERE request.type = 'GET'), 0)
                            FROM duckdb_logs_parsed('HTTP')""").fetchone()
                        assert counted is not None
                        requests, read = counted
                        con.close()

                    s3_ms = statistics.median(times) * 1e3
                    row |= {"s3_ms": s3_ms, "requests": requests, "mb_read": read / 1e6}
                    line += f" {s3_ms:9.1f} {requests:9d} {read / 1e6:8.1f}"

                print(line, flush=True)
                results.append(row)

    (root / f"queries-{'-'.join(streams)}.json").write_text(
        json.dumps(results, indent=1)
    )


