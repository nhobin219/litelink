def peak_rss(code: str) -> tuple[float, float]:
    """Run `code` in a fresh interpreter; its peak RSS in MB over the baseline
    of the imports, and its wall time."""
    prelude = (
        "import time, resource, json, sys\nimport pyarrow as pa, pyarrow.parquet as pq, duckdb\n"
        f"sys.path.insert(0, {str(Path(__file__).parent)!r})\nimport compaction as c\n"
        "base = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss\nstarted = time.perf_counter()\n"
    )
    epilogue = (
        "\nprint('RSS', json.dumps([resource.getrusage(resource.RUSAGE_SELF).ru_maxrss, base,"
        " time.perf_counter() - started]))"
    )
    out = subprocess.run(
        [sys.executable, "-c", prelude + code + epilogue],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    # Found, not taken as the last line: DuckDB's progress bar can precede it.
    peak, base, elapsed = json.loads(out[out.rindex("RSS ") + 4 :].splitlines()[0])
    return peak / 1024, elapsed  # ru_maxrss is KiB on Linux; the imports are in it too


def memory(root: Path) -> None:
    """Peak RSS of each way to write one compacted file, in a fresh process.

    in-memory   today's `_write_merge`: read every input, concatenate,
                re-sort, one `write_table` — at 1, 2, 4 and 8 of today's
                files as input (64 MiB to 512 MiB of Arrow)
    append      a streamed append of today's files into one 512 MB file
    k-way merge depth's inputs, each sorted by (symbol, ts), merged into one
                512 MB file
    ext. sort   the same re-sort by DuckDB's external sort, on 8 inputs
                only: at 512 MB the spill outgrew this box's free disk
    """
    base, _ = peak_rss("pass")
    print(f"MEMORY  peak RSS in a fresh process; the imports alone are {base:.0f} MB\n")
    print(
        f"  {'what':34s} {'input MB':>9s} {'arrow MiB':>10s} {'peak MB':>8s} {'secs':>6s}"
    )
    with tempfile.TemporaryDirectory(dir=root) as tmp:
        for stream, order in LAYOUT_STREAMS.items():
            today = sorted((root / stream / "today").glob("*.parquet"))
            for k in (1, 2, 4, 8):
                inputs = [str(p) for p in today[:k]]
                code = (
                    f"t = pa.concat_tables([pq.read_table(p) for p in {inputs!r}])\n"
                    f"t = c.sorted_by(t, {order!r})\n"
                    f"c.write(t, c.Path({tmp!r}) / 'merge.parquet')\n"
                )
                peak, secs = peak_rss(code)
                size = sum(Path(p).stat().st_size for p in inputs)
                print(
                    f"  {stream + ' in-memory x' + str(k):34s} {size / 1e6:9.1f} {k * 64:10d} {peak:8.0f} {secs:6.1f}",
                    flush=True,
                )

            # As many inputs as make one 512 MB output.
            per = statistics.mean(p.stat().st_size for p in today)
            inputs = [str(p) for p in today[: int(DISK_TARGET / per) + 1]]
            size = sum(Path(p).stat().st_size for p in inputs)
            code = (
                f"r = c.Rolling(c.Path({tmp!r}) / 'append', c.DISK_TARGET)\n"
                f"for p in {inputs!r}:\n    r.append(pq.read_table(p))\n"
                "r.close()\n"
            )
            peak, secs = peak_rss(code)
            print(
                f"  {stream + ' append -> 512 MB':34s} {size / 1e6:9.1f} {len(inputs) * 64:10d} {peak:8.0f} {secs:6.1f}",
                flush=True,
            )

            if stream == "depth":
                code = f"c.k_way_merge([c.Path(p) for p in {inputs!r}], c.Path({tmp!r}) / 'merged', {order!r})\n"
                peak, secs = peak_rss(code)
                label = f"{stream} k-way merge -> 512 MB"
                print(
                    f"  {label:34s} {size / 1e6:9.1f} {len(inputs) * 64:10d} {peak:8.0f} {secs:6.1f}",
                    flush=True,
                )
                few = inputs[:8]
                for limit in ("256MB", "1GB"):
                    code = (
                        f"c.external_sort([c.Path(p) for p in {few!r}], c.Path({tmp!r}) / 'sorted-{limit}',"
                        f" {order!r}, {limit!r})\n"
                    )
                    peak, secs = peak_rss(code)
                    label = f"{stream} ext. sort {limit}"
                    few_size = sum(Path(p).stat().st_size for p in few)
                    print(
                        f"  {label:34s} {few_size / 1e6:9.1f} {len(few) * 64:10d} {peak:8.0f} {secs:6.1f}",
                        flush=True,
                    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("phase", choices=["ratios", "layouts", "queries", "memory"])
    parser.add_argument(
        "--root", type=Path, default=Path(tempfile.gettempdir()) / "litelink-compaction"
    )
    parser.add_argument("--reps", type=int, default=5)
    parser.add_argument(
        "--stream",
        action="append",
        choices=list(LAYOUT_STREAMS),
        help="queries: only these",
    )
    parser.add_argument(
        "--no-s3",
        action="store_true",
        help="skip the S3 runs (rustfs at 127.0.0.1:9000)",
    )
    args = parser.parse_args()
    args.root.mkdir(parents=True, exist_ok=True)
    if args.phase == "ratios":
        ratios()
    elif args.phase == "layouts":
        layouts(args.root)
    elif args.phase == "queries":
        queries(
            args.root, args.reps, not args.no_s3, args.stream or list(LAYOUT_STREAMS)
        )
    else:
        memory(args.root)


if __name__ == "__main__":
    main()
