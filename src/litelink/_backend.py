"""The storage capabilities used by the buffer coordinator."""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any, NoReturn, Protocol

if TYPE_CHECKING:
    from collections.abc import Callable, Iterable, Iterator, Sequence
    from contextlib import AbstractContextManager

    import pyarrow as pa

    from litelink._table import PublishedCatalog
    from litelink._transaction import CallerTransaction


class Cursor(Protocol):
    def execute(
        self, sql: str, parameters: Sequence[Any] | Mapping[str, Any] = (), /
    ) -> Cursor: ...
    def executemany(
        self, sql: str, parameters: Iterable[Sequence[Any]], /
    ) -> Cursor: ...
    def __iter__(self) -> Iterator[Any]: ...
    def fetchone(self) -> Any: ...
    def fetchall(self) -> list[Any]: ...
    def close(self) -> None: ...
    @property
    def rowcount(self) -> int: ...


@dataclass(frozen=True)
class BackendErrors:
    integrity: type[Exception]
    absent: type[Exception]
    any: type[Exception]


PreparedRow = tuple[Mapping[str, object], tuple[object, ...], int]


class BufferBackend(Protocol):
    readonly: bool
    compacting_outputs: str
    errors: BackendErrors

    def write(self) -> AbstractContextManager[Cursor]: ...
    def read(self) -> AbstractContextManager[Cursor]: ...
    def savepoint(
        self, tx: CallerTransaction | None
    ) -> AbstractContextManager[Cursor]: ...
    def tail(self) -> Cursor: ...
    def sealer(self) -> Cursor: ...
    def create(self, schema: pa.Schema) -> None: ...
    def sql(self, text: str) -> str: ...
    def insert_id(self, cursor: Cursor, sql: str, params: Sequence[object]) -> int: ...
    def insert_rows(
        self,
        cursor: Cursor,
        sql: str,
        rows: Iterable[PreparedRow],
        refuse: Callable[[PreparedRow, BaseException], NoReturn],
    ) -> Iterator[tuple[PreparedRow, int]]: ...
    def next(self, cursor: Cursor) -> int: ...
    def seed(self, cursor: Cursor, first: int) -> None: ...
    def floor(self, cursor: Cursor) -> int: ...
    def advance(self, cursor: Cursor, n: int) -> tuple[int, int]: ...
    def caller_transaction(self, cursor: Cursor) -> CallerTransaction: ...
    def reclaim(self, min_free_ratio: float) -> int: ...
    def published_catalog(self) -> PublishedCatalog: ...
    def close(self) -> None: ...
